"""JSON, безопасный для вставки внутрь <script> в index.html.

Генераторы кладут данные в index.html блоками вида `const X = {...};`
и `<script type="application/ld+json">`. HTML-парсер обрывает <script>
на первой же последовательности `</script>` в тексте — даже если с точки
зрения JS она находится внутри строкового литерала. Обычный json.dumps
такие последовательности не трогает, поэтому имя города или описание из
Википедии вида `</script><img src=q onerror=...>` вырвалось бы из скрипта
и стало разметкой (хранимый XSS у всех посетителей).

\\u003c и соседи — валидные JSON-эскейпы: JSON.parse и JS-литерал видят
ровно те же символы, меняется только запись. U+2028/U+2029 экранируются
отдельно: в JSON они допустимы сырыми, а в JS-литерале до ES2019 это
разрыв строки.
"""
import json

_SUBS = (
    ("<", "\\u003c"),
    (">", "\\u003e"),
    ("&", "\\u0026"),
    ("\u2028", "\\u2028"),
    ("\u2029", "\\u2029"),
)


def json_for_script(obj, **kwargs) -> str:
    """json.dumps + нейтрализация последовательностей, значимых для HTML-парсера."""
    kwargs.setdefault("ensure_ascii", False)
    out = json.dumps(obj, **kwargs)
    for src, dst in _SUBS:
        out = out.replace(src, dst)
    return out
